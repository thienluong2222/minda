def check_status(waves: list[str]) -> int:
    reqs = _wave_requirements()
    missing = 0
    for w in waves:
        print(f"\n=== Wave {w} Inputs ===")
        for label, path, hint in reqs[w]:
            ok = path.exists()
            status = "OK     " if ok else "MISSING"
            rel = path.relative_to(ROOT) if path.is_relative_to(ROOT) else path
            print(f"[{status}] {label}: {rel}")
            if not ok:
                missing += 1
                print(f"          -> {hint}")
    return missing


def prepare_waves(waves: list[str]) -> None:
    setup_root_src()
    vivos_ready = (ROOT / "data/external/vivos").is_dir()

    if ("1" in waves or "3" in waves) and not (CB_DATA / "text/manifest.json").is_file():
        from experiments.comparative_benchmark import text as cb_text

        _run_module_step("comparative_benchmark.text.prepare", cb_text.prepare)

    if not vivos_ready:
        log(
            "[Prepare] data/external/vivos chưa có - bỏ qua sinh manifest audio/OCR từ VIVOS. "
            "Tải bằng: .venv-backend/bin/meeting-pipeline data fetch "
            "--manifest manifests/vivos.json"
        )
        return

    if ("1" in waves or "2" in waves or "3" in waves) and not (
        CB_DATA / "simulation/manifest.json"
    ).is_file():
        from experiments.comparative_benchmark import synthetic as cb_syn

        _run_module_step("comparative_benchmark.synthetic.meetings", cb_syn.meetings)

    if "1" in waves and not (CB_DATA / "ocr/manifest.json").is_file():
        from experiments.comparative_benchmark import ocr as cb_ocr

        _run_module_step("comparative_benchmark.ocr.prepare", cb_ocr.prepare)

    if ("2" in waves or "3" in waves) and not (CB_DATA / "asr/manifest.json").is_file():
        from experiments.comparative_benchmark import asr as cb_asr

        _run_module_step("comparative_benchmark.asr.prepare", cb_asr.prepare)
        _run_module_step(
            "comparative_benchmark.asr.prepare_synthetic",
            cb_asr.prepare_synthetic,
        )

    if "3" in waves and not (CB_DATA / "separation/manifest.json").is_file():
        from experiments.comparative_benchmark import separation as cb_sep

        _run_module_step("comparative_benchmark.separation.prepare", cb_sep.prepare)


def main() -> None:
    parser = argparse.ArgumentParser(description="Prepare and check Wave 1-3 benchmark inputs.")
    parser.add_argument(
        "--wave",
        choices=["1", "2", "3", "all"],
        default="all",
        help="Target benchmark wave to check or prepare.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Only check input availability without generating missing files.",
    )
    args = parser.parse_args()
    waves = ["1", "2", "3"] if args.wave == "all" else [args.wave]

    if not args.check:
        prepare_waves(waves)

    missing = check_status(waves)
    if missing:
        print(f"\nCòn thiếu {missing} mục đầu vào (xem hướng dẫn ở từng dòng MISSING phía trên).")
        if args.check:
            raise SystemExit(1)
    else:
        print("\nTất cả đầu vào cho các đợt đã chọn đều sẵn sàng.")


if __name__ == "__main__":
    main()
