def _run_module_step(label: str, fn) -> bool:
    try:
        log(f"[Prepare] Running {label} ...")
        fn()
        log(f"[Prepare] OK: {label}")
        return True
    except Exception as exc:
        log(f"[Prepare] FAILED ({label}): {exc}")
        return False


